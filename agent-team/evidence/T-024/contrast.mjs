import { COLORS } from '../../../src/render.js';

const channel = (hex, i) => {
  const c = parseInt(hex.slice(1 + 2 * i, 3 + 2 * i), 16) / 255;
  return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
};
const luminance = (hex) => 0.2126 * channel(hex, 0) + 0.7152 * channel(hex, 1) + 0.0722 * channel(hex, 2);
const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

console.log('%s', `dim ${COLORS.dim} on background ${COLORS.background}: ${ratio(COLORS.dim, COLORS.background).toFixed(2)}:1 (WCAG 2 relative luminance)`);
